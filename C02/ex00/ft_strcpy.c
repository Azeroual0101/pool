#include <unistd.h>

char	*ft_strcpy(char *dest, char *src)
{
	int		i;
	char	c;

	i = 0;
	while (src[i] != '\0')
	{
		c = src[i];
		dest[i] = c;
		i++;
	}
	dest[i] = '\0';
	return (dest);
}
